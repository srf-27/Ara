use std::net::{Ipv4Addr, SocketAddr};
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use ara::config::{ClientConfig, ResolvedConfig};
use ara::{TUN_MTU, VIRTUAL_PREFIX};
use clap::{Parser, Subcommand};
use futures_util::{SinkExt, StreamExt};
use tokio::sync::{mpsc, oneshot};
use tun::{create_as_async, TunPacket};

#[derive(Parser)]
#[command(name = "ara", about = "Ara P2P virtual LAN")]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
#[allow(clippy::large_enum_variant)]
enum Command {
    /// Join (or create) a room and bring up the TUN device.
    Up {
        /// TOML config file (default: ./ara.toml if present).
        #[arg(long)]
        config: Option<PathBuf>,
        /// Legacy M1/M2 network name.
        #[arg(long)]
        network: Option<String>,
        /// Legacy M1/M2 shared secret.
        #[arg(long)]
        secret: Option<String>,
        /// Server host, optionally host:port.
        #[arg(long)]
        server: Option<String>,
        /// Local UDP port shared by STUN and WireGuard (0 = ephemeral).
        #[arg(long)]
        port: Option<u16>,
        /// Local TCP port for direct-TCP fallback (default: same as --port).
        #[arg(long)]
        tcp_port: Option<u16>,
        /// Identity key file override (default: per-user platform path).
        #[arg(long)]
        identity: Option<PathBuf>,
        /// Room code to join.
        #[arg(long)]
        room: Option<String>,
        /// Room password (required with --create).
        #[arg(long)]
        password: Option<String>,
        /// Display name shown to other room members.
        #[arg(long)]
        nickname: Option<String>,
        /// Create a new room with a generated code.
        #[arg(long)]
        create: bool,
        /// Access file generated by `ara-server gen-access`.
        #[arg(long)]
        access: Option<PathBuf>,
    },
    /// Offline direct mode: connect to one peer by IP, no server/room.
    IpConnect {
        /// Peer address, IP:port.
        #[arg(long)]
        peer: String,
        /// Peer public key (base64, shown by `ara id` or the peer's GUI).
        #[arg(long)]
        peer_key: String,
        /// Peer virtual IP, e.g. 10.99.0.3.
        #[arg(long)]
        peer_vip: String,
        /// Own virtual IP, e.g. 10.99.0.2.
        #[arg(long)]
        vip: String,
        #[arg(long)]
        nickname: Option<String>,
    },
    /// Print this device's public key (the ID shared with peers).
    Id,
    /// List rooms visible on the server using an access file.
    Rooms {
        #[arg(long)]
        access: PathBuf,
    },
    /// Send one file to a room member (VIP or VIP:port).
    Send {
        #[arg(long)]
        to: String,
        #[arg(long)]
        file: PathBuf,
    },
    /// Receive incoming file transfers into a directory.
    Recv {
        #[arg(long)]
        dir: PathBuf,
        #[arg(long, default_value_t = ara::transfer::TRANSFER_PORT)]
        port: u16,
        /// Accept requests without an interactive prompt.
        #[arg(long)]
        auto_accept: bool,
    },
}

#[tokio::main]
async fn main() -> Result<()> {
    tracing_subscriber::fmt()
        .with_ansi(false)
        .with_target(false)
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "info,wintun::log=off".into()),
        )
        .init();
    let cli = Cli::parse();
    match cli.command {
        Command::Rooms { access } => return list_rooms(&access).await,
        Command::Id => {
            println!("{}", ara::client::own_public_key(None));
            return Ok(());
        }
        Command::Send { to, file } => {
            let addr: SocketAddr = to
                .parse()
                .or_else(|_| format!("{to}:{}", ara::transfer::TRANSFER_PORT).parse())?;
            return ara::transfer::send(addr, file).await;
        }
        Command::Recv { dir, port, auto_accept } => {
            return ara::transfer::serve(dir, port, auto_accept).await;
        }
        Command::IpConnect { peer, peer_key, peer_vip, vip, nickname } => {
            let peer_addr: SocketAddr = peer.parse().context("--peer must be IP:port")?;
            let own_vip: Ipv4Addr = vip.parse().context("invalid --vip")?;
            let peer_ip: Ipv4Addr = peer_vip.parse().context("invalid --peer-vip")?;
            let cfg = ResolvedConfig {
                network: String::new(),
                secret: String::new(),
                server_host: String::new(),
                server_port: 0,
                local_port: 0,
                tcp_port: 0,
                identity_path: None,
                room_code: String::new(),
                room_password: String::new(),
                access_token: String::new(),
                server_pub: String::new(),
                server_cert_pem: String::new(),
                nickname: nickname.unwrap_or_default(),
                create_room: false,
                direct_peer_addr: Some(peer_addr),
                direct_peer_key: peer_key,
                direct_peer_vip: Some(peer_ip),
                direct_vip: Some(own_vip),
            };
            let (from_tun_tx, from_tun_rx) = mpsc::channel::<Vec<u8>>(256);
            let (to_tun_tx, to_tun_rx) = mpsc::channel::<Vec<u8>>(256);
            let (assigned_tx, assigned_rx) = oneshot::channel();
            let client =
                tokio::spawn(ara::client::run_direct(cfg, from_tun_rx, to_tun_tx, assigned_tx, None));
            let vip = assigned_rx.await.context("direct mode failed to start")?;
            let result = run_tun(vip, from_tun_tx, to_tun_rx).await;
            client.abort();
            return result;
        }
        Command::Up {
            config,
            network,
            secret,
            server,
            port,
            tcp_port,
            identity,
            room,
            password,
            nickname,
            create,
            access,
        } => {
            let file_cfg = match config {
                Some(path) => ClientConfig::from_file(&path)?,
                None => {
                    let default = PathBuf::from("ara.toml");
                    if default.exists() {
                        ClientConfig::from_file(&default)?
                    } else {
                        ClientConfig::default()
                    }
                }
            };
            let cfg = file_cfg
                .merge_cli(
                    network, secret, server, port, tcp_port, identity, room, password, nickname,
                    create, access,
                )
                .validate()?;
            let (from_tun_tx, from_tun_rx) = mpsc::channel::<Vec<u8>>(256);
            let (to_tun_tx, to_tun_rx) = mpsc::channel::<Vec<u8>>(256);
            let (assigned_tx, assigned_rx) = oneshot::channel();
            let client = tokio::spawn(async move {
                if let Err(e) = ara::client::run(cfg, from_tun_rx, to_tun_tx, assigned_tx, None).await {
                    eprintln!("client stopped: {e:#}");
                }
            });
            let vip = assigned_rx
                .await
                .context("failed to join room (wrong password/full room, or client exited; see logs)")?;
            let result = run_tun(vip, from_tun_tx, to_tun_rx).await;
            client.abort();
            return result;
        }
    }
}

async fn run_tun(
    vip: Ipv4Addr,
    from_tun_tx: mpsc::Sender<Vec<u8>>,
    mut to_tun_rx: mpsc::Receiver<Vec<u8>>,
) -> Result<()> {
    #[cfg(target_os = "windows")]
    ensure_wintun().context("prepare wintun.dll")?;

    let mut config = tun::configure();
    config
        .name("ara")
        .address(vip)
        .netmask(prefix_mask(VIRTUAL_PREFIX))
        .mtu(TUN_MTU as i32)
        .layer(tun::Layer::L3)
        .up();
    let device = create_as_async(&config).context(
        "create TUN device (Windows: run as administrator; Linux: run as root)",
    )?;
    tracing::info!("TUN device up with {vip}/{VIRTUAL_PREFIX}, MTU {TUN_MTU}");
    let (mut tun_sink, mut tun_stream) = device.into_framed().split();

    tokio::spawn(async move {
        while let Some(pkt) = tun_stream.next().await {
            match pkt {
                Ok(p) => {
                    if from_tun_tx.send(p.get_bytes().to_vec()).await.is_err() {
                        break;
                    }
                }
                Err(e) => {
                    tracing::warn!("TUN read: {e}");
                    break;
                }
            }
        }
    });
    tokio::spawn(async move {
        while let Some(bytes) = to_tun_rx.recv().await {
            if tun_sink.send(TunPacket::new(bytes)).await.is_err() {
                break;
            }
        }
    });

    tracing::info!("ara is running; press Ctrl+C to stop");
    tokio::signal::ctrl_c().await?;
    tracing::info!("shutting down");
    Ok(())
}

async fn list_rooms(access: &Path) -> Result<()> {
    let af: ara::config::AccessFile = serde_json::from_str(
        &std::fs::read_to_string(access)
            .with_context(|| format!("read access file {}", access.display()))?,
    )
    .context("parse access file")?;
    let rooms = ara::client::fetch_rooms(&af.server, &af.cert_pem, &af.token, &af.server_pub).await?;
    for r in rooms {
        println!("{}  creator={}  {}/{}", r.code, r.creator, r.members, r.limit);
    }
    Ok(())
}

fn prefix_mask(prefix: u8) -> std::net::Ipv4Addr {
    let mask: u32 = if prefix == 0 { 0 } else { u32::MAX << (32 - prefix) };
    std::net::Ipv4Addr::from(mask)
}

/// The wintun crate loads wintun.dll from the exe directory; embed the official
/// signed DLL and extract it on first run so the binary is self-contained.
#[cfg(target_os = "windows")]
fn ensure_wintun() -> Result<()> {
    const DLL: &[u8] = include_bytes!("../vendor/wintun.dll");
    let exe = std::env::current_exe().context("locate exe")?;
    let dll = exe.parent().context("exe dir")?.join("wintun.dll");
    if !dll.exists() {
        std::fs::write(&dll, DLL).context("extract wintun.dll next to ara.exe")?;
    }
    Ok(())
}
